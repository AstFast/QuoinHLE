/// One interface the host serves out of its own table instead of the generated ones.
///
/// These are the interfaces the generated table does not carry — everything Brew MP added after
/// the classic headers were frozen. Registering one is what makes it **routable, nameable and
/// callable** from a single entry: [`host_iface`] resolves its index, [`label`] names its slots and
/// `Hle::vtable` builds its table. `Runtime` keeps the other half (which door answers a slot); the
/// two halves are joined by [`HostIface::index`], which is why the index is written down here and
/// nowhere else.
///
/// Before this existed, each interface was five edits in five places — a predicate in `dispatch`,
/// a block in `label_table`, a `vtable_*` builder in `hle`, its call site, and the entry in this
/// file — and nothing checked that the five agreed. The checks in `HOST_BY_INDEX` are compile-time,
/// so a sixth interface can now only be added *consistently*.
pub struct HostIface {
    /// Where this table's slots live: `(index << 12) | slot`.
    pub index: usize,
    /// Every published name this one table answers to, shallowest first. [`iface_index`] resolves
    /// any of them, so `Hle::vtable_named` works for these the way it does for a generated one.
    pub names: &'static [&'static str],
    /// `(the interface that declares the slot, method name)`, in slot order.
    pub methods: &'static [(&'static str, &'static str)],
}

/// The host-served interfaces, one entry each.
///
/// Order carries no meaning: the door that answers a slot is chosen by `index` in `Runtime`, and
/// `label` writes each entry to its own row. The indices still descend from `PROC_IFACE` because
/// the stub page is 16 MiB and the reserved ranges sit at the top of it — see the assert above.
pub static HOST_IFACES: &[HostIface] = &[
    HostIface {
        index: PORT1_IFACE,
        names: &["IPort1"],
        methods: &PORT1_METHODS,
    },
    HostIface {
        index: SENSORUTIL_IFACE,
        names: &["ISensorUtil"],
        methods: &SENSORUTIL_METHODS,
    },
    HostIface {
        index: MEMCACHE1_IFACE,
        names: &["IMemCache1"],
        methods: &MEMCACHE1_METHODS,
    },
    HostIface {
        index: SETTINGS_IFACE,
        names: &["ISettings"],
        methods: &SETTINGS_METHODS,
    },
    HostIface {
        index: VECTORMODEL_IFACE,
        names: &["IModel", "IListModel", "IVectorModel"],
        methods: &VECTORMODEL_METHODS,
    },
    HostIface {
        index: CANVAS_IFACE,
        names: &["ICanvas", "IDisplayCanvas"],
        methods: &CANVAS_METHODS,
    },
    HostIface {
        index: VALUEMODEL_IFACE,
        names: &["IModel", "IValueModel"],
        methods: &VALUEMODEL_METHODS,
    },
];

/// "No host interface at this index" in [`HOST_BY_INDEX`].
const HOST_SLOT_NONE: u8 = u8::MAX;

/// Dense position lookup by interface index: 1 KiB, one load, no comparison chain.
///
/// Built from [`HOST_IFACES`] rather than written by hand, and every way an entry can be wrong is a
/// **compile-time** failure: an index inside the generated range would shadow a real interface, a
/// duplicate would route one interface's slots to another's door, and an index at or above
/// `HELPER_IFACE` would build stubs outside the stub page. The ascent is what used to be six
/// hand-written `is_*_id` predicates, each of which had to be kept in step with its own assert.
static HOST_BY_INDEX: [u8; HELPER_IFACE + 1] = {
    let mut table = [HOST_SLOT_NONE; HELPER_IFACE + 1];
    let mut i = 0;
    while i < HOST_IFACES.len() {
        let index = HOST_IFACES[i].index;
        assert!(
            index >= IFACE_COUNT,
            "a host interface cannot sit inside the generated index range"
        );
        assert!(
            index < HELPER_IFACE,
            "an index at or above the helper index builds stubs outside the stub page"
        );
        assert!(
            index != PROC_IFACE && index != HOST_FN_IFACE,
            "reserved interface index"
        );
        assert!(table[index] == HOST_SLOT_NONE, "two host interfaces claim one index");
        table[index] = i as u8;
        i += 1;
    }
    table
};

const _: () = assert!(HOST_IFACES.len() < HOST_SLOT_NONE as usize);

/// The host-served interface at `index`, if the host serves one there.
#[inline]
pub fn host_iface(index: usize) -> Option<&'static HostIface> {
    match HOST_BY_INDEX.get(index) {
        Some(&pos) if pos != HOST_SLOT_NONE => Some(&HOST_IFACES[pos as usize]),
        _ => None,
    }
}

/// Whether `index` is one of [`HOST_IFACES`].
#[inline]
pub const fn is_host_iface(index: usize) -> bool {
    index < HOST_BY_INDEX.len() && HOST_BY_INDEX[index] != HOST_SLOT_NONE
}

/// The struct the loader points at with the word just below `AEEMod_Load`.
pub const HELPER_STRUCT: &str = "AEEHelperFuncs";

/// Dispatch id for the helper field at byte offset `off`.
pub const fn helper_id(off: u32) -> u32 {
    method_id(HELPER_IFACE, off / POINTER_SIZE as u32)
}

#[inline]
pub const fn is_helper_id(id: u32) -> bool {
    iface_of_method_id(id) == HELPER_IFACE
}

/// The `AEEHelperFuncs` field an id names, e.g. `"malloc"`.
///
/// `struct_info` walks the 594-entry generated table comparing names, and this is asked three
/// times per stdlib trap (`label`, `helper_field` again, and `Runtime::helper`). The struct never
/// changes, so resolve it once.
static HELPER_INFO: std::sync::OnceLock<&'static StructInfo> = std::sync::OnceLock::new();

pub fn helper_field(id: u32) -> Option<&'static FieldInfo> {
    let index = slot_of_method_id(id) as usize;
    HELPER_INFO
        .get_or_init(|| {
            struct_info(HELPER_STRUCT).expect("AEEHelperFuncs is in the generated tables")
        })
        .fields
        .get(index)
}

/// The published name of a class id, e.g. `"AEECLSID_FILEMGR"`, or `None` for an id the SDK does
/// not declare. An applet's own class id is `#define`d in the app and never lands here, which is
/// what makes the two kinds separable without a hand-written list.
pub fn clsid_name(cls: u32) -> Option<&'static str> {
    CONST_TABLE
        .iter()
        .find(|c| c.value == cls && c.name.starts_with("AEECLSID_"))
        .map(|c| c.name)
}

/// Whether `cls` names a service of the handset rather than a class some module declares.
pub fn is_system_class(cls: u32) -> bool {
    clsid_name(cls).is_some()
}

/// Every label is a pure function of the dispatch id, and the dispatch path asks for one on
/// **every** trap — a shipped game reaches the host tens of thousands of times a minute. Building
/// a `String` there put `format!`, a clone into `last_call`, another clone into the call log and
/// a `String` hash into the hottest host loop. Intern the finite table once instead: `label` is
/// now two array indexes and a `&'static str` copy, with no allocation on the hot path.
///
/// Ids are `(iface << 12) | slot` and the interface space reaches `HELPER_IFACE = 0x3ff`, so a
/// flat vector indexed by id would need 67 M entries. One bucket per interface keeps it to 1 024
/// short vectors, each indexed by the 12-bit slot.
struct LabelTable {
    by_iface: Vec<Vec<&'static str>>,
    /// Ids the generated tables do not name (a stub page address someone disassembled by hand,
    /// an EGL proc number, a host function past the reserved range). No taken trap lands here;
    /// one interning allocation per distinct odd id is fine on a diagnostic path.
    odd: std::sync::Mutex<std::collections::HashMap<u32, &'static str>>,
}

static LABELS: std::sync::OnceLock<LabelTable> = std::sync::OnceLock::new();

fn intern(s: String) -> &'static str {
    Box::leak(s.into_boxed_str())
}

fn label_table() -> &'static LabelTable {
    LABELS.get_or_init(|| {
        let mut by_iface = vec![Vec::new(); HELPER_IFACE + 1];
        for (index, iface) in IFACES.iter().enumerate() {
            by_iface[index] = iface
                .methods
                .iter()
                .map(|m| intern(format!("{}::{}", iface.name, m.name)))
                .collect();
        }
        if let Some(info) = struct_info(HELPER_STRUCT) {
            by_iface[HELPER_IFACE] = info
                .fields
                .iter()
                .map(|f| intern(format!("{}::{}", HELPER_STRUCT, f.name)))
                .collect();
        }
        // Host-function numbers are handed out as the run arms callbacks, so there is no
        // generated count to size this bucket from. Cover far more than a run ever needs;
        // anything past it takes the cold path below and stays correct.
        by_iface[HOST_FN_IFACE] = (0..256).map(|n| intern(format!("host#{n}"))).collect();
        // Interfaces the host serves itself have no generated entry, but they do have a table:
        // one row each, in slot order, named for the interface that declares the slot (a table
        // that answers two names says which name owns which slot). This used to be six blocks kept
        // in step with six predicates in `Runtime::dispatch_inner`; both ends read `HOST_IFACES`.
        for host in HOST_IFACES {
            by_iface[host.index] = host
                .methods
                .iter()
                .map(|(iface, name)| intern(format!("{iface}::{name}")))
                .collect();
        }
        // PROC_IFACE and any other gap have no published names: `method_label` used to emit
        // `method#{id:#08x}` for them, and the cold path still does.
        LabelTable {
            by_iface,
            odd: std::sync::Mutex::new(std::collections::HashMap::new()),
        }
    })
}

/// Name of the method or helper field an id dispatches to, for traces and error text.
///
/// The returned string lives for the whole process: it is safe to keep in a call record, print
/// after the run, or hand to a fault report without cloning.
pub fn label(id: u32) -> &'static str {
    let table = label_table();
    let iface = iface_of_method_id(id);
    let slot = slot_of_method_id(id) as usize;
    if let Some(&name) = table.by_iface.get(iface).and_then(|names| names.get(slot)) {
        return name;
    }
    let mut odd = table
        .odd
        .lock()
        .unwrap_or_else(std::sync::PoisonError::into_inner);
    if let Some(&name) = odd.get(&id) {
        return name;
    }
    let name = if is_helper_id(id) {
        intern(format!("helper#{id:#08x}"))
    } else if iface == HOST_FN_IFACE {
        intern(format!("host#{slot}"))
    } else {
        intern(format!("method#{id:#08x}"))
    };
    odd.insert(id, name);
    name
}

/// Human-readable name of the interface an id belongs to.
pub fn iface_name_of(id: u32) -> Option<&'static str> {
    iface_at(iface_of_method_id(id)).map(|i| i.name)
}

pub fn method(id: u32) -> Option<&'static MethodInfo> {
    IFACES
        .get(iface_of_method_id(id))?
        .methods
        .get(slot_of_method_id(id) as usize)
}

/// `"IShell::StartApplet"` for trace output.
pub fn method_label(id: u32) -> String {
    match (iface_at(iface_of_method_id(id)), method(id)) {
        (Some(i), Some(m)) => format!("{}::{}", i.name, m.name),
        _ => format!("method#{id:#08x}"),
    }
}

pub fn const_value(name: &str) -> Option<u32> {
    CONST_TABLE.iter().find(|c| c.name == name).map(|c| c.value)
}

/// The first name carrying `value` among the names that start with `prefix`, for reading a word
/// back out of a report. The prefix is what makes the answer mean something: `0xe035` is
/// `AVK_SELECT`, and searching without it would also land on whatever else shares the number.
/// `None` says no name in the table has that value under that prefix — which is the honest answer
/// for a word that turned out to be a pointer, a size, or the pack's own constant.
pub fn const_name(prefix: &str, value: u32) -> Option<&'static str> {
    CONST_TABLE
        .iter()
        .find(|c| c.value == value && c.name.starts_with(prefix))
        .map(|c| c.name)
}

pub fn enum_value(name: &str) -> Option<i32> {
    ENUMS.iter().find(|e| e.name == name).map(|e| e.value)
}

pub fn struct_info(name: &str) -> Option<&'static StructInfo> {
    STRUCTS.iter().find(|s| s.name == name)
}

pub fn offset_of(struct_name: &str, field: &str) -> Option<u32> {
    struct_info(struct_name)?
        .fields
        .iter()
        .find(|f| f.name == field)
        .map(|f| f.off)
}

/// `(byte offset, bit offset, width)` of a bitfield member, or `None` when the field is an
/// ordinary one. `AEEDeviceInfo`'s nine `b*` flags share one word at offset 28, so answering
/// `IShell::GetDeviceInfo` needs the bit position, not just the word.
pub fn bitfield_of(struct_name: &str, field: &str) -> Option<(u32, u32, u32)> {
    struct_info(struct_name)?
        .fields
        .iter()
        .find(|f| f.name == field && f.bits != 0)
        .map(|f| (f.off, f.bit_off, f.bits))
}

pub fn iface_for_iid(iid: u32) -> Option<&'static str> {
    IID_TO_IFACE
        .iter()
        .find(|(v, _)| *v == iid)
        .map(|(_, i)| *i)
}

/// Interfaces that expose `method`; used to recover intent from a raw vtable offset.
pub fn implementors(method: &str) -> Vec<&'static str> {
    IFACES
        .iter()
        .filter(|i| i.methods.iter().any(|m| m.name == method))
        .map(|i| i.name)
        .collect()
}

