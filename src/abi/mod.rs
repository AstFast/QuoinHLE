/// A method id is the HLE dispatch key carried in an `SVC` immediate: interface index in the
/// high bits, vtable slot in the low 12.
pub const fn method_id(iface: usize, slot: u32) -> u32 {
    ((iface as u32) << 12) | slot
}

pub const fn iface_of_method_id(id: u32) -> usize {
    (id >> 12) as usize
}

pub const fn slot_of_method_id(id: u32) -> u32 {
    id & 0x0fff
}

pub fn resolve_alias(name: &str) -> &str {
    IFACE_ALIAS
        .iter()
        .find(|(from, _)| *from == name)
        .map_or(name, |(_, to)| to)
}

pub fn iface_index(name: &str) -> Option<usize> {
    let target = resolve_alias(name);
    if let Some(index) = IFACES.iter().position(|i| i.name == target) {
        return Some(index);
    }
    // An interface the host serves itself has no generated entry, but it does have a table and a
    // name. Resolving it here is what makes `Hle::vtable_named("IPort1")` behave like any other
    // name, instead of every caller needing to know which side of the table it lives on.
    HOST_IFACES
        .iter()
        .find(|h| h.names.contains(&target))
        .map(|h| h.index)
}

pub fn iface(name: &str) -> Option<&'static IfaceInfo> {
    IFACES.iter().find(|i| i.name == resolve_alias(name))
}

pub fn iface_at(index: usize) -> Option<&'static IfaceInfo> {
    IFACES.get(index)
}

/// The vtable slot for a method by name, following inheritance.
pub fn slot_of(iface_name: &str, method: &str) -> Option<u32> {
    iface(iface_name)
        .and_then(|i| i.methods.iter().find(|m| m.name == method))
        .map(|m| m.slot)
}

/// The dispatch key for `Iface::Method`, which is also its stub's address in the stub page.
pub fn method_of(iface_name: &str, method: &str) -> Option<u32> {
    let index = iface_index(iface_name)?;
    Some(method_id(index, slot_of(iface_name, method)?))
}

/// The stdlib import table (`AEEHelperFuncs`) is dispatched with the same id scheme as an
/// interface vtable, but it is not an interface. This index is far past [`IFACE_COUNT`] and
/// still small enough that `id * 4` lands inside the stub page.
pub const HELPER_IFACE: usize = 0x03ff;

const _: () = assert!(IFACE_COUNT < HELPER_IFACE && HELPER_IFACE < (1 << 20));

/// Dispatch ids for **functions the host itself supplies** as callable addresses.
///
/// A few delivered bodies store a runtime C function into a block the pack owns — `SockSource_Readable`
/// writes `SockSource_ReadbleCancel` into the caller's `pfnCancel`, `CQueue`/`IQoSSession` write their
/// own cancel legs the same way — and the pack then calls it with `CALLBACK_CANCEL`. On a handset that
/// address is code; here it is the `SVC` stub page, so these ids are how the same call comes back to
/// the host. The index sits above the helper table's, which is above every published interface, and
/// `slot` is the host function's number.
pub const HOST_FN_IFACE: usize = 0x03fe;

/// Proc-address stubs handed out by `eglGetProcAddress`. This is a separate dispatch space:
/// the returned function is called with `EGLDisplay` in `r0`, not with a HLE object, so it
/// cannot go through an interface vtable.
pub const PROC_IFACE: usize = 0x03fd;

const _: () = assert!(IFACE_COUNT < PROC_IFACE && PROC_IFACE < HOST_FN_IFACE);

