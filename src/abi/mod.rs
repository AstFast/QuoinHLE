// ⚠ It sits **below** the helper index, not above it: the stub page is 16 MiB (`STUB_BASE..
// VTABLE_BASE`), which is ids up to `0x3f_ffff`, and `HELPER_IFACE = 0x3ff` already spends the top of
// it (`0x3ff << 12 << 2` lands at `0x01ff_c000`). The first try put these at `0x400` and every stub
// address came out as `0x0200_0000` — the vtable page — so a call faulted instead of dispatching.
const _: () = assert!(IFACE_COUNT < HOST_FN_IFACE && HOST_FN_IFACE < HELPER_IFACE);

