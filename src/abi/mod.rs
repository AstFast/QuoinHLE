//! Typed access to the ABI tables the host answers from.
//!
//! Every number here was harvested and emitted from published BREW headers rather
//! than hand-transcribed — that is what keeps the emulator honest about its own
//! ABI claims, and what lets a claim be checked by reading the tables instead of trusting a summary.
//!
//! **The tables are the source of truth in this tree.** They are compiled in (nothing here reads a
//! file at run time), and `crate::test::abi` pins the properties a wrong edit would break: slot
//! order, alias resolution, the host registry, the ids the headers publish. The pipeline that
//! produced them is a maintainer tool and is not part of this repository, so the banner inside
//! [`generated`] — which asks for a re-run — cannot be followed from a checkout. Treat those files as
//! source that happens to be machine-written: change them together with a test that pins why.

